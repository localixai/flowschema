/// Whether `c` is a combining mark, which no label may start with (RFC 5891, 4.2.3.2).
pub(super) fn is_mark(c: u32) -> bool {
    MARKS.partition_point(|&start| start <= c) % 2 == 1
}

/// Whether `c` is a virama.
pub(super) fn is_virama(c: u32) -> bool {
    VIRAMAS.binary_search(&c).is_ok()
}
